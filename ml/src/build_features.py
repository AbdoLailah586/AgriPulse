"""T13 — Orchestrate T09-T12 into a single versioned feature table + data dictionary.

Run: python build_features.py
Output: data/processed/features_v1.parquet, ml/reports/data_dictionary.md
"""

import json
import time

import pandas as pd

import features
from config import (
    DEFAULT_WARNING_WINDOW_MIN,
    PROCESSED_DIR,
    REPORTS_DIR,
    SENSOR_PREFIX,
    STATUS_COL,
    TS_COL,
    WARNING_WINDOWS_MIN,
)
from data_cleaning import clean, load_raw
from labeling import add_all_label_windows

VERSION = "v1"


def main():
    t0 = time.time()
    raw = load_raw()
    cleaned, clean_report = clean(raw)
    print(f"[1/5] cleaned: {cleaned.shape} ({time.time() - t0:.1f}s)")

    labeled = add_all_label_windows(cleaned)
    print(f"[2/5] labeled: {labeled.shape} ({time.time() - t0:.1f}s)")

    sensor_cols = [
        c
        for c in cleaned.columns
        if c.startswith(SENSOR_PREFIX) and not c.endswith("_was_missing")
    ]

    rf = features.rolling_features(labeled, sensor_cols)
    print(f"[3/5] rolling features: +{rf.shape[1]} cols ({time.time() - t0:.1f}s)")

    ef = features.ewm_features(labeled, sensor_cols)
    ff = features.fft_features(labeled)  # restricted sensor subset, see config.FFT_CANDIDATE_SENSORS
    groups = features.sensor_groups(labeled, sensor_cols)
    gf = features.cross_sensor_ratio_features(labeled, groups)
    print(
        f"[4/5] ewm/fft/cross-sensor: +{ef.shape[1] + ff.shape[1] + gf.shape[1]} cols "
        f"({time.time() - t0:.1f}s)"
    )

    final = pd.concat([labeled, rf, ef, ff, gf], axis=1)
    print(f"[5/5] final table: {final.shape} ({time.time() - t0:.1f}s)")

    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    out_path = PROCESSED_DIR / f"features_{VERSION}.parquet"
    final.to_parquet(out_path)
    print(f"Wrote {out_path} ({out_path.stat().st_size / 1e6:.1f} MB)")

    _write_data_dictionary(final, clean_report, groups, out_path)


def _write_data_dictionary(df: pd.DataFrame, clean_report: dict, groups: dict, out_path):
    label_cols = [f"label_{w}" for w in WARNING_WINDOWS_MIN]
    rul_cols = [f"rul_{w}" for w in WARNING_WINDOWS_MIN]

    lines = [
        f"# Data dictionary — {out_path.name}",
        "",
        f"Generated by `ml/src/build_features.py`. Shape: {df.shape[0]} rows x {df.shape[1]} cols.",
        "",
        "## Identity / target columns",
        f"- `{TS_COL}`: minute-level timestamp, 2018-04-01 to 2018-08-31, no gaps (verified in ml/reports/profile_report.json)",
        f"- `{STATUS_COL}`: raw machine status (NORMAL/RECOVERING/BROKEN) from the source CSV",
        f"- `{', '.join(label_cols)}`: derived WARNING/BROKEN/RECOVERING/NORMAL label per horizon (6h/8h/12h) — see labeling.py",
        f"- `{', '.join(rul_cols)}`: minutes-to-failure, defined only inside the matching WARNING window — see labeling.py",
        f"- default modeling horizon: {DEFAULT_WARNING_WINDOW_MIN} min (12h), per docs/",
        "",
        "## Sensor handling (T09) — see ml/reports/sensor_handling.md for full detail",
        f"- Dropped: {list(clean_report['dropped'].keys())} (100% missing)",
        f"- Missingness-indicator columns added (long gaps, NOT imputed — see module docstring in data_cleaning.py): "
        f"{clean_report['missing_indicator_cols']}",
        "",
        "## Feature families (T12)",
        "- `<sensor>_roll{15,60,360}_{mean,std,min,max,range,skew}`: rolling time-domain stats over 15min/1h/6h",
        "- `<sensor>_ewm15_mean`: exponentially-weighted mean, 15min span",
        "- `<sensor>_fft60_{dominant_bin,energy}`: rolling 1h spectral features, restricted to "
        "config.FFT_CANDIDATE_SENSORS (hypothesized vibration/current sensors — not all 52, for cost control)",
        "- `group_N_<a>_over_<b>`: cross-sensor ratio within correlation-clustered groups (threshold 0.8)",
        "",
        "## Sensor groups (correlation-clustered, >=2 members, threshold 0.8)",
        "Labeled neutrally (group_0, group_1, ...) since sensor semantics are anonymized in the "
        "source data — docs/ physical names (vibration, pressure, thermal, electrical) are a "
        "hypothesis to validate against the FMEA knowledge base later (WS3/WS4), not ground truth.",
        "",
    ]
    for gname, members in groups.items():
        lines.append(f"- `{gname}`: {members}")

    lines += [
        "",
        "## Known caveats",
        "- RECOVERING rows carry a label but are excluded from train/val splits (validation.py) "
        "per docs/: neither normal nor pre-failure, not a useful supervised target.",
        "- Only 7 failure events total — any per-fold metric (validation.py, leave-one-failure-out) "
        "is a single-event result, not a statistically robust estimate. Report event-level results "
        "individually, never averaged as if from a large test set.",
        "- sensor_50 and sensor_51 have multi-day contiguous gaps overlapping breakdown events #7 "
        "and #5 respectively — those two sensors contribute no signal for those two specific events "
        "regardless of model choice (see data_cleaning.py docstring).",
    ]

    (REPORTS_DIR / "data_dictionary.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {REPORTS_DIR / 'data_dictionary.md'}")


if __name__ == "__main__":
    main()
